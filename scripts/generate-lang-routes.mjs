#!/usr/bin/env node
// NOTE: Writes assets/data/lang-routes.js from scripts/lib/lang-routes.mjs (keep nav + hreflang in sync).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { NAV_LANG_ROUTES } from './lib/lang-routes.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'assets/data/lang-routes.js');

const body = Object.entries(NAV_LANG_ROUTES)
  .map(([from, to]) => `  '${from}': '${to}',`)
  .join('\n');

const js = `// NOTE: Bidirectional NO ↔ EN public path pairs for the language switch.
// Generated by scripts/generate-lang-routes.mjs — edit scripts/lib/lang-routes.mjs instead.
// Keys and values are extensionless canonical paths (trailing slash only on homes).
window.LANG_ROUTES = {
${body}
};
`;

fs.writeFileSync(out, js);
console.log(`Wrote ${path.relative(root, out)} (${Object.keys(NAV_LANG_ROUTES).length} routes).`);
